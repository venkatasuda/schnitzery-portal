const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('../../.audit-db/node_modules/@electric-sql/pglite');
const branch='00000000-0000-0000-0000-000000000010', other='00000000-0000-0000-0000-000000000011';
const manager='00000000-0000-0000-0000-000000000001', staff='00000000-0000-0000-0000-000000000002';
(async()=>{
  const db=new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; grant usage on schema auth to authenticated,service_role;
    create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create function is_manager() returns boolean language sql as $$select auth.uid()='${manager}'::uuid$$;
    create function accessible_branch_ids() returns setof uuid language sql as $$select '${branch}'::uuid$$;
    create table inventory_counts(id uuid default gen_random_uuid() primary key,branch_id uuid,product text,ist numeric);
    create table inventory_purchases(id uuid default gen_random_uuid() primary key,branch_id uuid,product text,qty numeric);
    create table waste_log(id uuid default gen_random_uuid() primary key,branch_id uuid,product text,qty numeric);
    create table stock_transfers(id uuid default gen_random_uuid() primary key,from_branch_id uuid,to_branch_id uuid,product text,qty numeric,status text);
    grant select,insert,update,delete on inventory_counts,inventory_purchases,waste_log,stock_transfers to authenticated;
    insert into waste_log(branch_id,product,qty) values('${branch}','Butter',2),('${other}','Foreign',3);`);
  await db.exec(fs.readFileSync('supabase/migrations/20261015040536_stock_event_history.sql','utf8'));
  assert.equal((await db.query("select count(*)::int n from stock_events where operation='BASELINE' and actor_id is null")).rows[0].n,2);
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${manager}',false)`);
  assert.equal((await db.query('select count(*)::int n from stock_events')).rows[0].n,1,'Foreign branch hidden');
  await db.exec(`insert into inventory_purchases(branch_id,product,qty) values('${branch}','Butter',5);
    insert into inventory_counts(branch_id,product,ist) values('${branch}','Butter',7);
    update waste_log set qty=4 where branch_id='${branch}';
    delete from waste_log where branch_id='${branch}';
    insert into stock_transfers(from_branch_id,to_branch_id,product,qty,status) values('${other}','${branch}','Butter',3,'requested');
    update stock_transfers set status='sent'; update stock_transfers set status='sent'; update stock_transfers set status='received';`);
  let events=(await db.query('select * from stock_events order by id')).rows;
  assert.equal(events.length,8,'No-op updates create no duplicate evidence');
  const deletion=events.find(e=>e.operation==='DELETE');
  assert.equal(deletion.before_row.qty,4);assert.equal(deletion.after_row,null);
  assert.equal(deletion.actor_id,manager,'Actor is authenticated identity, not submitted name');
  assert.equal(events.find(e=>e.source_table==='inventory_counts').after_row.ist,7,'Count retained as observation');
  assert.deepEqual(events.filter(e=>e.source_table==='stock_transfers').map(e=>e.after_row.status),['requested','sent','received']);
  await assert.rejects(db.exec("insert into stock_events(source_table) values('waste_log')"),/permission denied/);
  await assert.rejects(db.exec('delete from stock_events'),/permission denied/);
  await assert.rejects(db.exec('select private.capture_stock_event()'),/permission denied/);
  const count=events.length;
  await db.exec(`begin; insert into waste_log(branch_id,product,qty) values('${branch}','Rolled back',1); rollback;`);
  assert.equal((await db.query('select count(*)::int n from stock_events')).rows[0].n,count,'Source rollback also rolls back evidence');
  await db.exec(`select set_config('request.jwt.claim.sub','${staff}',false)`);
  assert.equal((await db.query('select count(*)::int n from stock_events')).rows[0].n,0,'Staff cannot read management journal');
  await db.exec("select set_config('request.jwt.claim.sub','',false)");
  await assert.rejects(db.exec(`insert into waste_log(branch_id,product,qty) values('${branch}','Unauthenticated',1)`),/Authenticated stock actor required/);
  await db.exec('reset role; grant update on stock_events to service_role; set role service_role');
  await assert.rejects(db.exec('update stock_events set actor_id=null'),/immutable/);
  await db.exec('reset role');
  assert.equal((await db.query("select count(*)::int n from waste_log where product='Unauthenticated'")).rows[0].n,0,'Audit failure prevents unaudited source write');
  await assert.rejects(db.exec('truncate stock_events'),/immutable/);
  await assert.rejects(db.exec('truncate waste_log'),/immutable/);
  await db.close();
  console.log('Stock baselines, all four writers, deleted evidence, actors, RLS, no-op updates, immutability and atomic rollback pass.');
})().catch(e=>{console.error(e);process.exitCode=1});
