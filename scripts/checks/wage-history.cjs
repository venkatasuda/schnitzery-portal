const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('../../.audit-db/node_modules/@electric-sql/pglite');
const actor='00000000-0000-0000-0000-000000000001', employee='00000000-0000-0000-0000-000000000002';
const foreign='00000000-0000-0000-0000-000000000003', branch='00000000-0000-0000-0000-000000000010', other='00000000-0000-0000-0000-000000000011';
(async()=>{
  const db=new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; grant usage on schema auth to authenticated,service_role;
    create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create table branches(id uuid primary key);
    create table users(id uuid primary key,branch_id uuid,role text,employee_code text,full_name text,team text);
    create function is_manager() returns boolean language sql as $$select exists(select 1 from public.users where id=auth.uid() and role in ('manager','branch_owner','brand_owner','super_admin'))$$;
    create function accessible_branch_ids() returns setof uuid language sql as $$select branch_id from public.users where id=auth.uid()$$;
    create table user_pay(user_id uuid primary key,branch_id uuid,hourly_wage numeric,updated_by uuid,updated_at timestamptz);
    create table payroll_settings(branch_id uuid primary key,ot_daily_hours numeric,night_start time,night_end time);
    create table attendance_logs(id uuid default gen_random_uuid() primary key,user_id uuid,branch_id uuid,work_date date,clock_in timestamptz,clock_out timestamptz,duration_mins integer,breaks jsonb,status text,approval_status text);
    create table payroll_runs(id uuid default gen_random_uuid() primary key,branch_id uuid,month text,status text,approved_by text,approved_at timestamptz,note text,unique(branch_id,month));
    grant all on all tables in schema public to service_role;
    grant select on users,branches,user_pay,payroll_settings,attendance_logs,payroll_runs to authenticated;
    grant insert,update,delete on user_pay to authenticated;
    insert into branches values('${branch}'),('${other}');
    insert into users values('${actor}','${branch}','manager','M','Manager','Kitchen'),('${employee}','${branch}','staff','E','Employee','Kitchen'),('${foreign}','${other}','staff','F','Foreign','Kitchen');
    insert into user_pay(user_id,branch_id,hourly_wage) values('${employee}','${branch}',20),('${foreign}','${other}',17);
    insert into attendance_logs(user_id,branch_id,work_date,clock_in,clock_out,duration_mins,breaks,status,approval_status) values
      ('${employee}','${branch}','2020-09-10','2020-09-10T08:00Z','2020-09-10T09:00Z',60,'[]','complete','approved'),
      ('${employee}','${branch}','2020-09-20','2020-09-20T08:00Z','2020-09-20T09:00Z',60,'[]','complete','approved');
  `);
  await db.exec(fs.readFileSync('supabase/migrations/20261012001000_payroll_approval_snapshots.sql','utf8'));
  await db.exec(`set role service_role; select set_config('request.jwt.claim.sub','${actor}',false)`);
  const inputs=async()=> (await db.query('select get_payroll_inputs($1,$2) value',[branch,'2020-09'])).rows[0].value;
  let current=await inputs();
  const legacy={month:'2020-09',revision:current.revision,rows:[{userId:employee,gross:40}],totals:{gross:40},settings:current.source.settings};
  await db.query('select set_payroll_approval_atomic($1,$2,$3,true,$4,$5,null)',[actor,branch,'2020-09',current.revision,legacy]);
  await db.exec('reset role');
  await db.exec(fs.readFileSync('supabase/migrations/20261013144029_wage_effective_history.sql','utf8'));
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${actor}',false)`);
  current=await inputs();
  assert.equal(current.source.wageBasis,'effective-dated');assert.ok(current.source.wages.every(w=>w.hourly_wage===null));
  assert.equal((await db.query('select count(*)::int n from wage_history')).rows[0].n,1,'Manager sees own branch only');
  await assert.rejects(db.query('select set_wage_effective($1,$2,$3,$4)',[actor,employee,20,'2020-09-01']),/permission denied/);
  await assert.rejects(db.query('update user_pay set hourly_wage=99'),/permission denied/);
  await assert.rejects(db.query('delete from wage_history'),/permission denied/);
  await db.exec('set role service_role');
  const rate=(w,date,user=employee,caller=actor)=>db.query('select set_wage_effective($1,$2,$3,$4)',[caller,user,w,date]);
  await assert.rejects(rate(20,'2020-09-01',employee,employee),/Managers only/);
  await assert.rejects(rate(20,'2020-09-01',foreign),/Not in your branch/);
  await assert.rejects(rate(-1,'2020-09-01'),/Invalid wage/);
  await assert.rejects(rate(20,null),/Invalid wage/);
  await assert.rejects(rate(20,'2100-01-01'),/Invalid wage/);
  await rate(20,'2020-09-01');await rate(25,'2020-09-15');await rate(18,'2020-08-01');
  assert.equal((await db.query('select hourly_wage from user_pay where user_id=$1',[employee])).rows[0].hourly_wage,'25','Backdated rate must not replace the latest current rate');
  current=await inputs();assert.deepEqual(current.source.wages.map(w=>w.hourly_wage),[20,25]);
  await rate(null,'2020-09-15');assert.equal((await inputs()).source.wages[1].hourly_wage,null,'Unset period must not fall back to an older rate');
  await rate(25,'2020-09-15');
  assert.equal((await db.query('select snapshot from payroll_approvals')).rows[0].snapshot.totals.gross,40,'Existing approval remains unchanged');
  await assert.rejects(db.query('update wage_history set hourly_wage=99'),/immutable/);
  const before=(await db.query('select count(*)::int n from wage_history')).rows[0].n;
  await db.exec('reset role');
  await db.exec("create function fail_wage() returns trigger language plpgsql as $$begin raise exception 'forced failure'; end$$; create trigger fail_wage before insert on user_pay for each row execute function fail_wage()");
  await db.exec('set role service_role');
  await assert.rejects(rate(30,'2020-09-20'),/forced failure/);
  assert.equal((await db.query('select count(*)::int n from wage_history')).rows[0].n,before,'Failed current-rate write rolls back its history entry');
  await db.exec('reset role; drop trigger fail_wage on user_pay; set role service_role');
  await db.query('select set_payroll_approval_atomic($1,$2,$3,false,$4,null,null)',[actor,branch,'2020-09',legacy.revision]);
  current=await inputs();
  const snapshot={month:'2020-09',wageBasis:'effective-dated',revision:current.revision,rows:[{userId:employee,gross:45}],totals:{gross:45},settings:current.source.settings};
  await assert.rejects(db.query('select set_payroll_approval_atomic($1,$2,$3,true,$4,$5,null)',[actor,branch,'2020-09',current.revision,{...snapshot,wageBasis:null}]),/updated payroll/);
  await db.query('select set_payroll_approval_atomic($1,$2,$3,true,$4,$5,null)',[actor,branch,'2020-09',current.revision,snapshot]);
  assert.equal((await db.query('select count(*)::int n from payroll_approvals')).rows[0].n,2);
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${employee}',false)`);
  assert.equal((await db.query('select count(*)::int n from wage_history where user_id<>$1',[employee])).rows[0].n,0,'Employee cannot read colleagues wages');
  console.log('Unknown baselines, dated lookup, backdating, private append-only history, rollback and frozen approvals pass.');
  await db.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
