const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('../../.audit-db/node_modules/@electric-sql/pglite');
const actor = '00000000-0000-0000-0000-000000000001';
const employee = '00000000-0000-0000-0000-000000000002';
const branch = '00000000-0000-0000-0000-000000000010';
const other = '00000000-0000-0000-0000-000000000011';
(async () => {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; grant usage on schema auth to authenticated, service_role;
    create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create table branches(id uuid primary key);
    create table users(id uuid primary key,branch_id uuid,role text,employee_code text,full_name text,team text);
    create function public.is_manager() returns boolean language sql as $$select exists(select 1 from public.users where id=auth.uid() and role in ('manager','branch_owner','brand_owner','super_admin'))$$;
    create function public.accessible_branch_ids() returns setof uuid language sql as $$select branch_id from public.users where id=auth.uid()$$;
    create table user_pay(user_id uuid primary key,branch_id uuid,hourly_wage numeric);
    create table payroll_settings(branch_id uuid primary key,ot_daily_hours numeric,night_start time,night_end time);
    create table attendance_logs(id uuid primary key,user_id uuid,branch_id uuid,work_date date,clock_in timestamptz,clock_out timestamptz,duration_mins integer,breaks jsonb,status text,approval_status text);
    create table payroll_runs(id uuid default gen_random_uuid() primary key,branch_id uuid,month text,status text,approved_by text,approved_at timestamptz,note text,unique(branch_id,month));
    grant all on all tables in schema public to service_role;
    grant select on users,branches,user_pay,payroll_settings,attendance_logs,payroll_runs to authenticated;
    grant insert,update,delete on payroll_runs to authenticated;
    insert into branches values('${branch}'),('${other}');
    insert into users values('${actor}','${branch}','manager','M1','Manager','Kitchen'),('${employee}','${branch}','staff','E1','Employee','Kitchen');
    insert into user_pay values('${employee}','${branch}',20);
    insert into attendance_logs values('${employee}','${employee}','${branch}','2026-09-10','2026-09-10T08:00Z','2026-09-10T09:00Z',60,'[]','complete','pending');
  `);
  await db.exec(fs.readFileSync('supabase/migrations/20261012001000_payroll_approval_snapshots.sql','utf8'));
  const inputs = async month => (await db.query('select get_payroll_inputs($1,$2) value',[branch,month])).rows[0].value;
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${actor}',false)`);
  let current = await inputs('2026-09');
  const snapshot = () => ({month:'2026-09',revision:current.revision,rows:[{userId:employee,paidH:1,wage:20,gross:20}],totals:{paidH:1,gross:20},settings:current.source.settings});
  const approve = (month='2026-09', revision=current.revision, value=snapshot()) => db.query('select set_payroll_approval_atomic($1,$2,$3,true,$4,$5,null)',[actor,branch,month,revision,value]);
  await assert.rejects(approve(),/permission denied/);
  await assert.rejects(db.query('insert into payroll_runs(branch_id,month,status) values($1,$2,$3)',[branch,'2026-09','approved']),/permission denied/);
  await assert.rejects(db.query('select get_payroll_inputs($1,$2)',[other,'2026-09']),/Branch access denied/);
  await db.exec('set role service_role');
  await assert.rejects(approve(),/Every completed shift/);
  await db.exec("update attendance_logs set approval_status='approved'");
  await assert.rejects(approve(),/Payroll changed/);
  current=await inputs('2026-09');
  await db.exec('update user_pay set hourly_wage=null');
  current=await inputs('2026-09');
  await assert.rejects(approve(),/valid wage/);
  await db.exec('update user_pay set hourly_wage=20');
  current=await inputs('2026-09');
  await assert.rejects(approve(new Date().toISOString().slice(0,7)),/Close the month/);
  await db.exec("reset role; create function forced_failure() returns trigger language plpgsql as $$begin raise exception 'forced failure'; end$$; create trigger fail_run before insert on payroll_runs for each row execute function forced_failure(); set role service_role");
  await assert.rejects(approve(),/forced failure/);
  assert.equal((await db.query('select count(*)::int n from payroll_approvals')).rows[0].n,0,'Snapshot insert must roll back when run update fails');
  await db.exec('reset role; drop trigger fail_run on payroll_runs; set role service_role');
  await approve();
  await assert.rejects(approve(),/Already approved/);
  const saved=(await db.query('select snapshot,source from payroll_approvals')).rows[0];
  await assert.rejects(db.query('update payroll_approvals set snapshot=$1',[{}]),/immutable/);
  await assert.rejects(db.query('select set_payroll_approval_atomic($1,$2,$3,false,null,null,null)',[employee,branch,'2026-09']),/Manager branch access denied/);
  await assert.rejects(db.query('select set_payroll_approval_atomic($1,$2,$3,false,null,null,null)',[actor,other,'2026-09']),/Manager branch access denied/);
  await db.exec('update user_pay set hourly_wage=99');
  assert.deepEqual((await db.query('select snapshot,source from payroll_approvals')).rows[0],saved);
  await assert.rejects(db.query('select set_payroll_approval_atomic($1,$2,$3,false,$4,null,null)',[actor,branch,'2026-09','stale']),/Approval changed/);
  await db.query('select set_payroll_approval_atomic($1,$2,$3,false,$4,null,null)',[actor,branch,'2026-09',current.revision]);
  assert.equal((await db.query('select count(*)::int n from payroll_approvals')).rows[0].n,1);
  await db.exec('set role authenticated');
  await assert.rejects(db.query('update payroll_approvals set snapshot=$1',[{}]),/permission denied/);
  await assert.rejects(db.query('delete from payroll_approvals'),/permission denied/);
  await db.exec(`reset role; update users set role='staff' where id='${actor}'; set role authenticated`);
  await assert.rejects(inputs('2026-09'),/Managers only/);
  assert.equal((await db.query('select count(*)::int n from payroll_approvals')).rows[0].n,0,'Staff cannot read archived wages');
  await db.close();
  console.log('Payroll approval gates, stale inputs, role/branch denial, rollback, frozen history and reopen retention pass.');
})().catch(error => { console.error(error); process.exitCode=1; });
